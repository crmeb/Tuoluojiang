namespace App\Http\Contract\Runtime;

/**
 * Swoole 请求态重置契约.
 *
 * 持有「仅当前 HTTP/MCP 请求有效」状态的服务应实现本接口，
 * 由 RequestStateCleaner 在请求间隙统一调用，避免跨请求串扰与内存残留。
 */
interface RequestScopedResettable
{
    /**
     * 清空本实例上的请求级状态（过滤器、缓冲、上下文缓存等）.
     */
    public function resetRequestState(): void;
}
